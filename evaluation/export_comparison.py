"""Export small, auditable synthetic benchmark results without runtime traces."""
import argparse
import datetime as dt
import hashlib
import json
from pathlib import Path

try:
    from evaluation.compare_agents import canonical_owner
except ModuleNotFoundError:
    from compare_agents import canonical_owner

ROOT = Path(__file__).resolve().parents[1]


def export_bundle(directory):
    specs = {s['name']: s for s in json.loads((ROOT / 'evaluation/agent_cases.json').read_text())['cases']}
    summaries = {m: json.loads((directory / m / 'summary.json').read_text()) for m in ('rules', 'agent')}
    if summaries['rules']['dataset_sha256'] != summaries['agent']['dataset_sha256']:
        raise ValueError('Different data snapshots cannot form a paired comparison.')
    names = [{r['name'] for r in summaries[m]['results']} for m in ('rules', 'agent')]
    if names[0] != names[1] or not names[0]:
        raise ValueError('Both modes must cover the same nonempty case set.')
    modes = {}
    for mode in ('rules', 'agent'):
        reports = []
        for row in summaries[mode]['results']:
            path = directory / mode / f"{row['name']}.json"
            raw = path.read_bytes()
            report = json.loads(raw)
            checks = dict(report['checks'])
            cases = list(report.get('case_store', {}).get('cases', {}).values())
            owner = cases[0].get('owner_team') if len(cases) == 1 else None
            expected_owner = specs[row['name']].get('expected_owner')
            notes = []
            if expected_owner:
                checks['owner'] = len(cases) == 1 and canonical_owner(owner) == canonical_owner(expected_owner)
                if checks['owner'] != report['checks'].get('owner'):
                    notes.append('Accepted documented playbook owner alias; original checks retained.')
            reports.append({k: report.get(k) for k in
                ('name', 'seconds', 'model_cycles', 'input_tokens', 'output_tokens', 'error', 'result')} |
                {'passed': all(checks.values()), 'checks': checks, 'original_checks': report['checks'],
                 'scoring_notes': notes, 'owner': owner, 'expected_owner': expected_owner,
                 'source_report_sha256': hashlib.sha256(raw).hexdigest(),
                 'tool_calls': [{'role': e['agent'], 'tool': e['tool']}
                                for e in report.get('events', []) if e['type'] == 'tool_call']})
        modes[mode] = {'cases': len(reports), 'passed': sum(r['passed'] for r in reports), 'results': reports}
    return {'exported_at': dt.datetime.now(dt.timezone.utc).isoformat(),
            'dataset_sha256': summaries['rules']['dataset_sha256'],
            'dataset_hash_scope': 'Deterministic synthetic returns.parquet; all fixtures generated by the same driver.',
            'paired': True, 'modes': modes, 'explanation_quality_reviewed': False,
            'limitations': ['Six seeded synthetic acceptance cases, not held-out accuracy.',
                'Pass checks cover routing, ownership, approvals and duplicate handling, not correctness of every explanation.',
                'Owner normalization accepts the explicit playbook alias only; raw checks are retained.',
                'No monetary billing, causal savings or production-scale performance has been established.']}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, required=True)
    parser.add_argument('--out', type=Path, default=ROOT / 'evaluation/results/agent_comparison.json')
    args = parser.parse_args()
    bundle = export_bundle(args.root)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(bundle, indent=2, ensure_ascii=False), encoding='utf-8')
    print(json.dumps({mode: {'passed': report['passed'], 'cases': report['cases']}
                      for mode, report in bundle['modes'].items()}))


if __name__ == '__main__':
    main()
